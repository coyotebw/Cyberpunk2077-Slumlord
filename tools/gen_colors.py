"""Generate r6/scripts/Slumlord/Colors.reds from the design-system colour tokens.

Usage: python tools/gen_colors.py [tokens.json] [out.reds]
Re-run whenever the design system's colours change. Do not edit Colors.reds by hand.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tools/design-tokens/tokens.json"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "r6/scripts/Slumlord/Colors.reds"


def resolve(name, table, seen=()):
    value = table[name]
    ref = re.fullmatch(r"\{([a-z0-9-]+)\}", value)
    if not ref:
        return value
    target = ref.group(1)
    if target in seen:
        raise ValueError(f"circular token reference: {name} -> {target}")
    return resolve(target, table, seen + (name,))


RESERVED = {"Void"}  # redscript type names that cannot be used as function names


def func_name(token):
    name = "".join(part.capitalize() for part in token.split("-"))
    return f"{name}Color" if name in RESERVED else name


def channels(hex_value):
    h = hex_value.lstrip("#")
    if len(h) != 6:
        raise ValueError(f"expected #rrggbb, got {hex_value}")
    return [int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4)]


def main():
    data = json.loads(TOKENS.read_text(encoding="utf-8"))
    table = {t["name"]: t["value"] for t in data["color"]["tokens"]}
    lines = [
        "// GENERATED by tools/gen_colors.py from the Slumlord UI Design System tokens.",
        "// Do not edit by hand. Re-run the generator after changing tokens.json.",
        "module Slumlord",
        "",
        "public abstract class SlumlordColors {",
    ]
    for name in table:
        hex_value = resolve(name, table)
        r, g, b = channels(hex_value)
        alias = "" if table[name] == hex_value else f" (alias of {table[name]})"
        lines.append(f"  // {name}: {hex_value}{alias}")
        lines.append(
            f"  public static func {func_name(name)}() -> HDRColor {{ "
            f"return new HDRColor({r:.4f}, {g:.4f}, {b:.4f}, 1.0); }}"
        )
    lines.append("")
    lines.append("  // Rank letter colour by rank index (0 = D ... 4 = S).")
    lines.append("  public static func ForRank(rank: Int32) -> HDRColor {")
    lines.append("    switch rank {")
    for idx, letter in enumerate("dcbas"):
        lines.append(f"      case {idx}: return SlumlordColors.Rank{letter.upper()}();")
    lines.append("      default: return SlumlordColors.RankD();")
    lines.append("    }")
    lines.append("  }")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(table)} colours)")


if __name__ == "__main__":
    main()
